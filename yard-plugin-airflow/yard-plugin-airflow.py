# ---------------------------------------------------------------------------
# Dispatch
# ---------------------------------------------------------------------------


def dispatch(request):
    """Route request to the appropriate handler by operation."""
    op = request.get("operation")
    if op == "validate":
        return handle_validate(request["job_name"], request["job_config"])
    elif op == "codegen":
        return handle_codegen(request["job_name"], request["job_config"])
    elif op == "deploy":
        return handle_deploy(
            request["job_name"], request["job_config"], request["artifact"]
        )
    elif op == "destroy":
        return handle_destroy(request["job_name"], request["resources"])
    elif op == "verify":
        return handle_verify(request["job_name"], request["resources"])
    elif op == "schema":
        return handle_schema()
    else:
        raise ValueError("unknown operation: {}".format(op))


# ---------------------------------------------------------------------------
# Protocol entry point (mirrors PluginServer::run from server.rs)
# ---------------------------------------------------------------------------


def main():
    """Protocol lifecycle: handshake -> read request -> dispatch -> respond -> exit."""
    try:
        # Step 1: Write handshake to stdout
        handshake = {
            "protocol_version": PROTOCOL_VERSION,
            "name": PLUGIN_NAME,
            "version": PLUGIN_VERSION,
            "capabilities": [
                "validate",
                "codegen",
                "deploy",
                "destroy",
                "verify",
                "schema",
            ],
        }
        sys.stdout.write(json.dumps(handshake) + "\n")
        sys.stdout.flush()

        # Step 2: Read request from stdin
        line = sys.stdin.readline()
        if not line.strip():
            log.error("no request received on stdin")
            sys.exit(1)

        request = json.loads(line.strip())

        # Step 3: Dispatch and write response
        response = dispatch(request)
        sys.stdout.write(json.dumps(response) + "\n")
        sys.stdout.flush()
        sys.exit(0)

    except Exception as exc:
        log.error("%s", exc)
        sys.exit(1)


if __name__ == "__main__":
    main()

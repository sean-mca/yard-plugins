def render_default_args(config):
    """Render the default_args dict for the DAG constructor.

    Only includes fields that are explicitly set (owner, retries).
    Returns '{}' when no default args are configured.
    """
    entries = []

    # Check default_args sub-dict first, then top-level config
    default_args = config.get("default_args", {})
    owner = default_args.get("owner") or config.get("owner")
    retries = default_args.get("retries")
    if retries is None:
        retries = config.get("retries")

    if owner:
        entries.append('    "owner": {},'.format(python_string_literal(owner)))
    if retries is not None:
        entries.append('    "retries": {},'.format(retries))

    if not entries:
        return "{}"
    return "{{\n{}\n}}".format("\n".join(entries))


def render_outlets(task_config, version):
    """Render outlets=[Class(uri)] kwarg fragment for tasks with publishes.

    Returns a formatted line (with leading 8-space indent and trailing newline)
    when the task has a 'publishes' list, or empty string otherwise.
    """
    publishes = task_config.get("publishes", [])
    if not publishes:
        return ""
    vi = VERSION_IMPORTS[version]
    outlets = ", ".join(
        "{}({})".format(vi["class_name"], python_string_literal(uri))
        for uri in publishes
    )
    return "        outlets=[{}],\n".format(outlets)


def render_task(task_id, task_config, version):
    """Render a single task assignment inside the 'with DAG(...)' block.

    Supports 'bash' and 'glue' task types. Raises ValueError for unsupported types.
    """
    var = python_var_name(task_id)
    tid = python_string_literal(task_id)
    vi = VERSION_IMPORTS[version]
    outlets_line = render_outlets(task_config, version)

    task_type = task_config.get("task_type", "")

    if task_type == "bash":
        cmd = task_config.get("command", "")
        return (
            "    {var} = BashOperator(\n"
            "        task_id={tid},\n"
            "        bash_command={cmd},\n"
            "{outlets}"
            "    )".format(
                var=var,
                tid=tid,
                cmd=python_string_literal(cmd),
                outlets=outlets_line,
            )
        )
    elif task_type == "glue":
        job_name = task_config.get("job_name", task_id)
        script_location = task_config.get("script_location", "")
        iam_role_arn = task_config.get("iam_role_arn", "")
        aws_conn_id = task_config.get("aws_conn_id", "aws_default")
        return (
            "    {var} = GlueJobOperator(\n"
            "        task_id={tid},\n"
            "        job_name={jn},\n"
            "        script_location={sl},\n"
            "        iam_role_arn={ir},\n"
            "        aws_conn_id={cn},\n"
            "{outlets}"
            "    )".format(
                var=var,
                tid=tid,
                jn=python_string_literal(job_name),
                sl=python_string_literal(script_location),
                ir=python_string_literal(iam_role_arn),
                cn=python_string_literal(aws_conn_id),
                outlets=outlets_line,
            )
        )
    else:
        raise ValueError(
            "task '{}': task_type '{}' is not supported in Airflow codegen yet".format(
                task_id, task_type
            )
        )



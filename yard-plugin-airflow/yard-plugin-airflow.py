_SANITIZE_RE = re.compile(r"[^A-Za-z0-9_]")


def sanitize_identifier(s):
    """Sanitize a string into a Python identifier fragment.

    Keep [A-Za-z0-9_], replace everything else with _, prepend _ if the first
    char is a digit. Return '_' if the result would be empty.
    """
    out = _SANITIZE_RE.sub("_", s)
    if not out:
        return "_"
    if out[0].isdigit():
        out = "_" + out
    return out


def python_var_name(task_id):
    """Convert a task id to a Python variable name: t_{sanitized}."""
    return "t_" + sanitize_identifier(task_id)


def python_string_literal(s):
    """Return a Python string literal using json.dumps (JSON strings are valid Python literals)."""
    return json.dumps(s)



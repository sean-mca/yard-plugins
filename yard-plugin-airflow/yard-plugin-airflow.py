def main():
    """Protocol lifecycle: handshake -> read request -> dispatch -> respond -> exit."""
    try:
        # Step 1: Write handshake to stdout
        handshake = {
            "protocol_version": PROTOCOL_VERSION,
            "name": PLUGIN_NAME,
            "version": PLUGIN_VERSION,
            "capabilities": [
                "validate",
                "codegen",
                "deploy",
                "destroy",
                "verify",
                "schema",
            ],
        }
        sys.stdout.write(json.dumps(handshake) + "\n")
        sys.stdout.flush()

        # Step 2: Read request from stdin
        line = sys.stdin.readline()
        if not line.strip():
            log.error("no request received on stdin")
            sys.exit(1)

        request = json.loads(line.strip())

        # Step 3: Dispatch and write response
        response = dispatch(request)
        sys.stdout.write(json.dumps(response) + "\n")
        sys.stdout.flush()
        sys.exit(0)

    except Exception as exc:
        log.error("%s", exc)
        # Write error response to stdout before exiting, matching Rust SDK behavior
        error_response = {"error": str(exc)}
        sys.stdout.write(json.dumps(error_response) + "\n")
        sys.stdout.flush()
        sys.exit(1)


if __name__ == "__main__":
    main()

def handle_validate(job_name, job_config):
    """Validate DAG configuration. Returns {'errors': [...]}."""
    errors = []

    # Rule: dags_bucket is required (D-10)
    dags_bucket = job_config.get("dags_bucket", "")
    if not dags_bucket:
        errors.append({
            "field": "dags_bucket",
            "message": "dags_bucket is required",
            "severity": "error",
        })

    # Rule: trigger and schedule mutual exclusion
    has_schedule = bool(job_config.get("schedule"))
    has_trigger = job_config.get("trigger") is not None
    if has_schedule and has_trigger:
        trigger = job_config["trigger"]
        # A schedule-type trigger inside trigger: is allowed with schedule field
        if not (isinstance(trigger, dict) and "schedule" in trigger):
            errors.append({
                "field": "trigger",
                "message": "trigger and schedule are mutually exclusive",
                "severity": "error",
            })

    # Rule: airflow_version must be 2 or 3 if present
    av = job_config.get("airflow_version")
    if av is not None and av not in (2, 3):
        errors.append({
            "field": "airflow_version",
            "message": "airflow_version must be 2 or 3",
            "severity": "error",
        })

    # Rule: trigger structure validation (T-05-02)
    trigger = job_config.get("trigger")
    if trigger is not None and isinstance(trigger, dict):
        recognized_keys = {"schedule", "dataset", "s3", "sqs", "api", "all", "any"}
        trigger_keys = set(trigger.keys()) & recognized_keys
        if not trigger_keys:
            errors.append({
                "field": "trigger",
                "message": (
                    "trigger must have one recognized key: "
                    "schedule, dataset, s3, sqs, api, all, or any"
                ),
                "severity": "error",
            })

        # S3 trigger: bucket must be non-empty
        if "s3" in trigger:
            s3 = trigger["s3"]
            if isinstance(s3, dict):
                bucket = s3.get("bucket", "")
                if not bucket:
                    errors.append({
                        "field": "trigger.s3.bucket",
                        "message": "S3 trigger bucket must be non-empty",
                        "severity": "error",
                    })

        # SQS trigger: queue_url must be non-empty
        if "sqs" in trigger:
            sqs = trigger["sqs"]
            if isinstance(sqs, dict):
                queue_url = sqs.get("queue_url", "")
                if not queue_url:
                    errors.append({
                        "field": "trigger.sqs.queue_url",
                        "message": "SQS trigger queue_url must be non-empty",
                        "severity": "error",
                    })

        # Composite triggers: items must be a non-empty list
        for comp_key in ("all", "any"):
            if comp_key in trigger:
                items = trigger[comp_key]
                if not isinstance(items, list) or len(items) == 0:
                    errors.append({
                        "field": "trigger.{}".format(comp_key),
                        "message": "composite trigger items must be a non-empty list",
                        "severity": "error",
                    })
                elif isinstance(items, list):
                    # Recurse into composite items for source-level validation
                    for idx, item in enumerate(items):
                        if not isinstance(item, dict):
                            continue
                        if "schedule" in item:
                            errors.append({
                                "field": "trigger.{}.{}".format(comp_key, idx),
                                "message": (
                                    "schedule source is not supported inside composite triggers; "
                                    "use a top-level schedule or trigger, not both"
                                ),
                                "severity": "error",
                            })
                        if "s3" in item:
                            s3 = item["s3"]
                            if isinstance(s3, dict) and not s3.get("bucket", ""):
                                errors.append({
                                    "field": "trigger.{}.{}.s3.bucket".format(comp_key, idx),
                                    "message": "S3 trigger bucket must be non-empty",
                                    "severity": "error",
                                })
                        if "sqs" in item:
                            sqs = item["sqs"]
                            if isinstance(sqs, dict) and not sqs.get("queue_url", ""):
                                errors.append({
                                    "field": "trigger.{}.{}.sqs.queue_url".format(comp_key, idx),
                                    "message": "SQS trigger queue_url must be non-empty",
                                    "severity": "error",
                                })
                    # Reject duplicate non-dataset source types (would produce
                    # duplicate Airflow task IDs that Airflow rejects at parse time)
                    source_types = [_source_kind(item) for item in items if isinstance(item, dict)]
                    non_dataset = [s for s in source_types if s and s != "dataset"]
                    if len(non_dataset) != len(set(non_dataset)):
                        errors.append({
                            "field": "trigger.{}".format(comp_key),
                            "message": "composite trigger cannot have duplicate non-dataset source types",
                            "severity": "error",
                        })

    # Rule: connection_id syntax validation (D-11)
    tasks = job_config.get("tasks", [])
    for task in tasks:
        conn_id = task.get("aws_conn_id") or task.get("connection_id")
        if conn_id is not None and (not isinstance(conn_id, str) or not conn_id.strip()):
            errors.append({
                "field": "connection_id",
                "message": "connection_id must be a non-empty string",
                "severity": "error",
            })

    return {"errors": errors}


def handle_codegen(job_name, job_config):
    """Generate an Airflow DAG Python file. Returns {'script': '...'}."""
    script = render_dag(job_name, job_config)
    return {"script": script}



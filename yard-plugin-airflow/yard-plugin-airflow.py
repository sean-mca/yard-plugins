def handle_validate(job_name, job_config):
    """Validate DAG configuration. Returns {'errors': [...]}."""
    errors = []

    # Rule: dags_bucket is required (D-10)
    dags_bucket = job_config.get("dags_bucket", "")
    if not dags_bucket:
        errors.append({
            "field": "dags_bucket",
            "message": "dags_bucket is required",
            "severity": "error",
        })

    # Rule: trigger and schedule mutual exclusion
    has_schedule = bool(job_config.get("schedule"))
    has_trigger = job_config.get("trigger") is not None
    if has_schedule and has_trigger:
        trigger = job_config["trigger"]
        # A schedule-type trigger inside trigger: is allowed with schedule field
        if not (isinstance(trigger, dict) and "schedule" in trigger):
            errors.append({
                "field": "trigger",
                "message": "trigger and schedule are mutually exclusive",
                "severity": "error",
            })

    # Rule: airflow_version must be 2 or 3 if present
    av = job_config.get("airflow_version")
    if av is not None and av not in (2, 3):
        errors.append({
            "field": "airflow_version",
            "message": "airflow_version must be 2 or 3",
            "severity": "error",
        })

    # Rule: connection_id syntax validation (D-11)
    tasks = job_config.get("tasks", [])
    for task in tasks:
        conn_id = task.get("aws_conn_id") or task.get("connection_id")
        if conn_id is not None and (not isinstance(conn_id, str) or not conn_id.strip()):
            errors.append({
                "field": "connection_id",
                "message": "connection_id must be a non-empty string",
                "severity": "error",
            })

    return {"errors": errors}


def handle_codegen(job_name, job_config):
    """Generate an Airflow DAG Python file. Returns {'script': '...'}."""
    script = render_dag(job_name, job_config)
    return {"script": script}



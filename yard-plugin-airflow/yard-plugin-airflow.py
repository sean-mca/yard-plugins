# ---------------------------------------------------------------------------
# Helper functions (ported from helpers.rs)
# ---------------------------------------------------------------------------

_SANITIZE_RE = re.compile(r"[^A-Za-z0-9_]")


def sanitize_identifier(s):
    """Sanitize a string into a Python identifier fragment.

    Keep [A-Za-z0-9_], replace everything else with _, prepend _ if the first
    char is a digit. Return '_' if the result would be empty.
    """
    out = _SANITIZE_RE.sub("_", s)
    if not out:
        return "_"
    if out[0].isdigit():
        out = "_" + out
    return out


def python_var_name(task_id):
    """Convert a task id to a Python variable name: t_{sanitized}."""
    return "t_" + sanitize_identifier(task_id)


def python_string_literal(s):
    """Return a Python string literal using json.dumps (JSON strings are valid Python literals)."""
    return json.dumps(s)


# ---------------------------------------------------------------------------
# Rendering helpers (ported from generation.rs)
# ---------------------------------------------------------------------------


def render_default_args(config):
    """Render the default_args dict for the DAG constructor.

    Only includes fields that are explicitly set (owner, retries).
    Returns '{}' when no default args are configured.
    """
    entries = []

    # Check default_args sub-dict first, then top-level config
    default_args = config.get("default_args", {})
    owner = default_args.get("owner") or config.get("owner")
    retries = default_args.get("retries")
    if retries is None:
        retries = config.get("retries")

    if owner:
        entries.append('    "owner": {},'.format(python_string_literal(owner)))
    if retries is not None:
        entries.append('    "retries": {},'.format(retries))

    if not entries:
        return "{}"
    return "{{\n{}\n}}".format("\n".join(entries))


def render_task(task_id, task_config, version):
    """Render a single task assignment inside the 'with DAG(...)' block.

    Supports 'bash' and 'glue' task types. Raises ValueError for unsupported types.
    """
    var = python_var_name(task_id)
    tid = python_string_literal(task_id)
    vi = VERSION_IMPORTS[version]

    task_type = task_config.get("task_type", "")

    if task_type == "bash":
        cmd = task_config.get("command", "")
        return (
            "    {var} = BashOperator(\n"
            "        task_id={tid},\n"
            "        bash_command={cmd},\n"
            "    )".format(
                var=var,
                tid=tid,
                cmd=python_string_literal(cmd),
            )
        )
    elif task_type == "glue":
        job_name = task_config.get("job_name", task_id)
        script_location = task_config.get("script_location", "")
        iam_role_arn = task_config.get("iam_role_arn", "")
        aws_conn_id = task_config.get("aws_conn_id", "aws_default")
        return (
            "    {var} = GlueJobOperator(\n"
            "        task_id={tid},\n"
            "        job_name={jn},\n"
            "        script_location={sl},\n"
            "        iam_role_arn={ir},\n"
            "        aws_conn_id={cn},\n"
            "    )".format(
                var=var,
                tid=tid,
                jn=python_string_literal(job_name),
                sl=python_string_literal(script_location),
                ir=python_string_literal(iam_role_arn),
                cn=python_string_literal(aws_conn_id),
            )
        )
    else:
        raise ValueError(
            "task '{}': task_type '{}' is not supported in Airflow codegen yet".format(
                task_id, task_type
            )
        )


def render_dag(job_name, job_config):
    """Main codegen entry point: render a complete Airflow DAG Python file.

    For Plan 1, supports schedule-only DAGs. Trigger support is added in Plan 2.
    """
    # D-06: default airflow version is 3
    version = job_config.get("airflow_version", 3)
    vi = VERSION_IMPORTS[version]

    schedule = job_config.get("schedule")
    tasks = job_config.get("tasks", [])

    # Determine which operator imports are needed
    needs_bash = False
    needs_glue = False
    for task in tasks:
        tt = task.get("task_type", "")
        if tt == "bash":
            needs_bash = True
        elif tt == "glue":
            needs_glue = True

    import_lines = []
    if needs_bash:
        import_lines.append(vi["bash_op_import"])
    if needs_glue:
        import_lines.append(
            "from airflow.providers.amazon.aws.operators.glue import GlueJobOperator"
        )
    imports_block = "\n".join(import_lines)

    # Render default_args
    default_args = render_default_args(job_config)

    # Schedule expression
    if schedule is not None:
        schedule_expr = python_string_literal(schedule)
    else:
        schedule_expr = "None"

    # max_active_runs -- empty for schedule-only DAGs (plan 1)
    max_active_runs = job_config.get("max_active_runs")
    if max_active_runs is not None:
        max_active_runs_block = "    max_active_runs={},\n".format(max_active_runs)
    else:
        max_active_runs_block = ""

    # Render tasks
    task_lines = []
    for task in tasks:
        tid = task.get("task_id", "")
        task_lines.append(render_task(tid, task, version))
    tasks_block = "\n".join(task_lines)

    # Dependency wiring
    dep_lines = []
    for task in tasks:
        tid = task.get("task_id", "")
        depends_on = task.get("depends_on", [])
        for upstream in depends_on:
            dep_lines.append("{} >> {}".format(python_var_name(upstream), python_var_name(tid)))

    if dep_lines:
        deps_block = "\n".join(dep_lines)
    else:
        deps_block = "# No task dependencies"

    # Trigger header block -- empty for schedule-only DAGs (Plan 1)
    trigger_header_block = ""

    # Required connections block -- empty for Plan 1
    required_connections_block = ""

    # Render via Jinja2
    env = Environment()
    template = env.from_string(DAG_TEMPLATE)
    return template.render(
        dag_name=job_name,
        trigger_header_block=trigger_header_block,
        required_connections_block=required_connections_block,
        imports_block=imports_block,
        default_args=default_args,
        schedule=schedule_expr,
        max_active_runs_block=max_active_runs_block,
        tasks_block=tasks_block,
        deps_block=deps_block,
    )


